#!/usr/bin/env bash
# AUR-361 / AC-001 - bootstrap action lock.
#
# DESIGN NOTE (round 3 redesign).
#
# Round 1 ASSERTED: a human wrote `entry_NNN_*` records into
# `.board/bootstrap/locks/actions.yml` and the gate decided pass/fail from
# whole-file digests only, so a stale entry set never blocked anything.
#
# Round 2 DERIVED the lock: the whole file is a pure function of the scanned
# bytes, produced by `--generate` in this same file, and the gate regenerates
# it into a temporary file and compares byte for byte. That killed "a field
# nobody recomputes" and it is KEPT here unchanged.
#
# Round 2 still lost to the surviving class: THE CHECK THAT NEVER RUNS. Two
# live bypasses were demonstrated inside the sealed container with exit 0:
#
#   B1  `owner_is_trusted` was called only when `entry_kind == remote`, so a
#       `uses: docker://evil-registry.example.com/malware@sha256:<64hex>` was
#       recorded with the literal owner string "docker" and never compared to
#       any allowlist.
#   B2  a `uses: ./path` was hashed for INTEGRITY but never OPENED, so a
#       composite action's own `uses:` lines were never derived, never
#       classified, and never policed.
#
# Both are the same defect: the program classified by BRANCH, one branch per
# input shape, and some branch skipped the check. Round 3 removes the branches
# instead of adding one more:
#
#   1. TRANSITIVE CLOSURE. `derive_lock` no longer enumerates a fixed file
#      list. It seeds a worklist with `.github/workflows/**` plus the root
#      `action.yml`, and every local `uses:` target discovered while scanning
#      is ENQUEUED into the same worklist, to a fixed point, with cycle
#      detection (an already-enqueued path is never re-enqueued; an already
#      visited path being dequeued twice is a hard reject) and with the
#      counts asserted: visited == enqueued == queue length. A second,
#      independent assertion in the entry phase proves every local entry's
#      resolved target is a member of the closed file set, so a scan that
#      missed an edge cannot pass silently.
#
#   2. ONE POLICY, ZERO BRANCHES. There is a single origin allowlist keyed by
#      (source, owner) and it is applied to EVERY derived entry with no
#      conditional whatsoever. `entry_kind` may change HOW the owner is
#      extracted; it can never change WHETHER the owner is checked. The loop
#      counts its own applications and refuses unless the count equals the
#      entry count, so "the check silently did not run" is itself a failure
#      mode with a typed code. An unknown source value fails closed.
#
# Emptiness is never success: zero input files, zero derived `uses:` sites, a
# missing live floor, or an empty allowlist are all explicit refusals.
#
# Reference truth is the workflow files. The lock is the derivative. The
# fixture suite under tests/bootstrap/locks/AUR-361 is checked against
# hand-written expectations in cases.tsv, which are NOT generated by this
# script, so no comparison in this file is a copy of the thing it verifies.
#
# One more finding of round 3, from mutation-testing THIS file: asserting only
# the typed code was not enough evidence. Several controls share the code
# `invalid_lock_or_manifest`, so deleting the `no-input-files` control or the
# `zero-uses-sites-derived` control left the suite green - a redundant control
# refused with the same code and no row could tell. That is the same class
# again, one level up: the check stopped running and nothing observed it. Each
# refusing fixture row therefore also names the exact control that must fire
# (`reason` column), asserted as a colon-delimited field of the detail, with
# the usual count assertion. Both mutants now die.

