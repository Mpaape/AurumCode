selector="${1:-AC-001}"
case "$selector" in
  AC-001|ContractAUR361|IntegrationAUR361|E2EAUR361) ;;
  --generate)
    tmp_root="$(mktemp -d "${TMPDIR:-/tmp}/aur361.XXXXXX")"
    trap 'rm -rf -- "$tmp_root"' EXIT
    if ! derive_lock "$repo_root" "$tmp_root/derived" true; then
      fail "$L361_CODE" "$L361_DETAIL"
    fi
    mkdir -p -- "$(dirname -- "$repo_root/$lock_path")"
    cat -- "$tmp_root/derived" >"$repo_root/$lock_path"
    chmod 0644 -- "$repo_root/$lock_path"
    printf 'AUR-361: regenerated %s (%s)\n' "$lock_path" "$(digest_of "$repo_root/$lock_path")"
    exit 0
    ;;
  *) printf '%s/%s/unknown-selector\n' "$card" "$scenario" >&2; exit 64 ;;
esac

tmp_root="$(mktemp -d "${TMPDIR:-/tmp}/aur361.XXXXXX")"
trap 'rm -rf -- "$tmp_root"' EXIT

# --- Phase 0: every declared path is present and actually read -------------
declared_paths=("$lock_path" "$fixture_dir" "$self_path" "$spec_path")
declared_read_bytes=0
declared_checked=0
for declared in "${declared_paths[@]}"; do
  target="$repo_root/$declared"
  [[ -e "$target" ]] || fail invalid_lock_or_manifest "declared-path-missing:$declared"
  [[ ! -L "$target" ]] || fail source_integrity_error "declared-path-is-symlink:$declared"
  if [[ -d "$target" ]]; then
    inner=0
    while IFS= read -r found; do
      [[ -n "$found" ]] || continue
      inner=$((inner + 1))
      declared_read_bytes=$((declared_read_bytes + $(byte_size_of "$found")))
    done < <(find "$target" -type f | sort)
    (( inner > 0 )) || fail invalid_lock_or_manifest "declared-path-empty:$declared"
  else
    b="$(byte_size_of "$target")"
    (( b > 0 )) || fail invalid_lock_or_manifest "declared-path-empty:$declared"
    declared_read_bytes=$((declared_read_bytes + b))
  fi
  declared_checked=$((declared_checked + 1))
done
(( declared_checked == ${#declared_paths[@]} )) ||
  fail invalid_lock_or_manifest "declared-path-loop-drift:$declared_checked"
(( declared_read_bytes > 0 )) ||
  fail invalid_lock_or_manifest 'declared-paths-read-zero-bytes'

# --- Phase 1: regenerate the whole lock and compare byte for byte ----------
if ! derive_lock "$repo_root" "$tmp_root/derived.lock" true; then
  fail "$L361_CODE" "$L361_DETAIL"
fi
derived_digest="$(digest_of "$tmp_root/derived.lock")"
committed_digest="$(digest_of "$repo_root/$lock_path")"
if ! cmp -s -- "$tmp_root/derived.lock" "$repo_root/$lock_path"; then
  drift_label="$(classify_drift "$repo_root/$lock_path")"
  fail "$drift_label" "lock-not-derived:committed=$committed_digest:derived=$derived_digest"
fi
[[ "$derived_digest" == "$committed_digest" ]] ||
  fail source_integrity_error "digest-disagrees-with-cmp:$committed_digest:$derived_digest"

# --- Phase 1b: the origin gate really ran, once per live entry -------------
# Positive control against "the check silently did not happen": the committed
# lock records how many times the single origin gate fired, and that number
# must equal the active site count, which must itself be non-zero.
live_active="$(sed -n 's/^active_site_count: \([0-9][0-9]*\)$/\1/p' "$repo_root/$lock_path" | head -n 1)"
live_checked="$(sed -n 's/^origin_policy_checked: \([0-9][0-9]*\)$/\1/p' "$repo_root/$lock_path" | head -n 1)"
[[ -n "$live_active" && -n "$live_checked" ]] ||
  fail invalid_lock_or_manifest 'lock-missing-policy-counters'
(( live_active > 0 )) ||
  fail invalid_lock_or_manifest "live-active-sites-zero:$live_active"
(( live_checked == live_active )) ||
  fail invalid_lock_or_manifest "live-origin-policy-drift:$live_checked/$live_active"

# --- Phase 2: fixture suite against hand-written expectations --------------
cases_file="$repo_root/$fixture_dir/cases.tsv"
[[ -f "$cases_file" && ! -L "$cases_file" ]] || fail invalid_lock_or_manifest 'cases-tsv-missing'
declared_rows="$(sed -n '/^[^#]/p' "$cases_file" | sed '/^$/d' | wc -l)"
declared_rows="${declared_rows//[[:space:]]/}"
(( declared_rows > 0 )) || fail invalid_lock_or_manifest 'cases-tsv-empty'

executed=0
reason_asserted=0
refusals_expected=0
while IFS=$'\t' read -r case_name want_exit want_code want_active want_inert want_idents want_reason; do
  [[ -n "$case_name" ]] || continue
  [[ "${case_name:0:1}" != '#' ]] || continue
  executed=$((executed + 1))
  # A row may not opt out of naming its control: a refusing row must carry a
  # reason and a passing row must not, or the column would be decoration that
  # a future edit could quietly empty.
  if [[ "$want_exit" == '1' ]]; then
    refusals_expected=$((refusals_expected + 1))
    [[ -n "$want_reason" && "$want_reason" != '-' ]] ||
      fail invalid_lock_or_manifest "fixture-reason-missing:$case_name"
  else
    [[ "$want_reason" == '-' ]] ||
      fail invalid_lock_or_manifest "fixture-reason-unexpected:$case_name:$want_reason"
  fi
  case_root="$repo_root/$fixture_dir/cases/$case_name"
  [[ -d "$case_root" ]] || fail invalid_lock_or_manifest "fixture-case-missing:$case_name"
  L361_CODE=''; L361_DETAIL=''
  if derive_lock "$case_root" "$tmp_root/case.lock" false; then
    got_exit=0; got_code='pass'
  else
    got_exit=1; got_code="$L361_CODE"
  fi
  [[ "$got_exit" == "$want_exit" ]] ||
    fail invalid_lock_or_manifest "fixture-exit:$case_name:want=$want_exit:got=$got_exit:code=$got_code"
  [[ "$got_code" == "$want_code" ]] ||
    fail invalid_lock_or_manifest "fixture-code:$case_name:want=$want_code:got=$got_code:$L361_DETAIL"
  if (( got_exit == 1 )); then
    detail_names_reason "$L361_DETAIL" "$want_reason" ||
      fail invalid_lock_or_manifest "fixture-reason:$case_name:want=$want_reason:detail=$L361_DETAIL"
    reason_asserted=$((reason_asserted + 1))
  fi
  if (( got_exit == 0 )); then
    got_active="$(sed -n 's/^active_site_count: \([0-9][0-9]*\)$/\1/p' "$tmp_root/case.lock" | head -n 1)"
    got_inert="$(sed -n 's/^inert_line_count: \([0-9][0-9]*\)$/\1/p' "$tmp_root/case.lock" | head -n 1)"
    got_checked="$(sed -n 's/^origin_policy_checked: \([0-9][0-9]*\)$/\1/p' "$tmp_root/case.lock" | head -n 1)"
    got_idents="$(sed -n 's/^entry_[0-9][0-9][0-9]_identity: \(.*\)$/\1/p' "$tmp_root/case.lock" | sort -u | tr '\n' ',' )"
    got_idents="${got_idents%,}"
    [[ "$got_active" == "$want_active" ]] ||
      fail invalid_lock_or_manifest "fixture-active:$case_name:want=$want_active:got=$got_active"
    [[ "$got_inert" == "$want_inert" ]] ||
      fail invalid_lock_or_manifest "fixture-inert:$case_name:want=$want_inert:got=$got_inert"
    [[ "$got_idents" == "$want_idents" ]] ||
      fail invalid_lock_or_manifest "fixture-identities:$case_name:want=$want_idents:got=$got_idents"
    # Same positive control as the live tree: a passing fixture must show the
    # origin gate firing once per active site, never zero.
    [[ "$got_checked" == "$got_active" ]] ||
      fail invalid_lock_or_manifest "fixture-origin-policy-drift:$case_name:$got_checked/$got_active"
  fi
done < <(sed -n '/^[^#]/p' "$cases_file" | sed '/^$/d')

(( executed == declared_rows )) ||
  fail invalid_lock_or_manifest "fixture-count:executed=$executed:declared=$declared_rows"
(( executed >= 36 )) ||
  fail invalid_lock_or_manifest "fixture-floor:executed=$executed"
# Count assertion beside the reason check: every expected refusal named its
# control, and there is at least one. Zero named controls is a failure, not a
# clean suite.
(( reason_asserted == refusals_expected )) ||
  fail invalid_lock_or_manifest "fixture-reason-drift:asserted=$reason_asserted:expected=$refusals_expected"
(( reason_asserted > 0 )) ||
  fail invalid_lock_or_manifest 'fixture-reason-never-asserted'

live_files="$(sed -n 's/^file_count: \([0-9][0-9]*\)$/\1/p' "$repo_root/$lock_path" | head -n 1)"
live_seeds="$(sed -n 's/^seed_file_count: \([0-9][0-9]*\)$/\1/p' "$repo_root/$lock_path" | head -n 1)"
printf '{"card":"%s","scenario":"%s","selector":"%s","lock_digest":"%s","seed_files":%s,"closure_files":%s,"active_sites":%s,"origin_checks":%s,"fixture_cases":%d,"named_controls":%d,"result":"pass"}\n' \
  "$card" "$scenario" "$selector" "$committed_digest" "$live_seeds" "$live_files" "$live_active" "$live_checked" "$executed" "$reason_asserted"
